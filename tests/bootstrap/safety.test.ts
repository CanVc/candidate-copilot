import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, URL } from 'node:url';
import { describe, expect, it } from 'vitest';
import viteConfig from '../../vite.config';

const root = fileURLToPath(new URL('../../', import.meta.url));
const ignoredPaths = [
  'node_modules/example.js', 'dist/frontend/index.html', 'dist/worker/index.js',
  'coverage/result.json', 'playwright-report/index.html', 'test-results/result.json',
  '.wrangler/state/db.sqlite', 'frontend/.wrangler/state.json',
  '.venv/bin/python', 'venv/bin/python', '.env', '.env.local', '.env.production',
  'frontend/.env.local', '.dev.vars', '.dev.vars.local',
  'content/private/preparation.md', 'content/private/nested/.env.example',
];

describe('publication boundaries', () => {
  it('disables frontend env/asset loading and Worker env-file discovery', () => {
    expect(viteConfig).toMatchObject({ appType: 'mpa', publicDir: false, envDir: false, envPrefix: [] });
    const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
    expect(manifest.scripts['build:worker']).toContain('--env-file /dev/null');
    // Inspect the command itself: inherited CI must not mask missing protection.
    expect(manifest.scripts['build:worker']).toContain('&& CI=true WRANGLER_SEND_METRICS=false wrangler deploy --dry-run');
    expect(manifest.scripts['build:frontend']).not.toContain('CI=true');
  });

  it('keeps startup loopback-only, strict and local with protected Worker settings', () => {
    expect(viteConfig.server).toMatchObject({
      host: '127.0.0.1', port: 5173, strictPort: true,
      proxy: { '/api': 'http://127.0.0.1:8787' },
      fs: { strict: true },
    });
    expect(viteConfig.server?.fs?.allow).toEqual([
      join(root, 'frontend/index.html'), join(root, 'frontend/src'), join(root, 'src/shared'),
    ]);
    expect(viteConfig.server?.fs?.deny).toEqual(expect.arrayContaining(['**/.env*', '**/.dev.vars*', '**/content/**', '**/docs/**', '**/public/**']));
    const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
    expect(manifest.scripts['dev:frontend']).toBe('vite');
    expect(manifest.scripts['dev:worker']).toBe('CI=true WRANGLER_SEND_METRICS=false wrangler dev --local --persist-to .wrangler/state --ip 127.0.0.1 --port 8787 --inspector-ip 127.0.0.1 --env-file /dev/null');
    expect(manifest.devDependencies['@playwright/test']).toBe('1.64.1');
    expect(manifest.scripts['test:smoke']).toBe('playwright test');
  });

  it('keeps local D1 commands and generated types behind explicit safety boundaries', () => {
    const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
    expect(manifest.scripts['db:init']).toBe('node scripts/local-d1.mjs init');
    expect(manifest.scripts['db:check']).toBe('node scripts/local-d1.mjs check');
    expect(manifest.scripts['db:types']).toBe('node scripts/local-d1.mjs types');
    expect(manifest.scripts['test:d1']).toBe('playwright test d1.spec.ts');
    const script = readFileSync(join(root, 'scripts/local-d1.mjs'), 'utf8');
    for (const protection of [
      "process.env.CI = 'true'", "process.env.WRANGLER_SEND_METRICS = 'false'",
      "'--config', 'wrangler.jsonc', '--env-file', '/dev/null'", "'--local', '--persist-to', '.wrangler/state'",
      "remoteBindings: false, envFiles: ['/dev/null']", "join(root, '.wrangler/state/v3')",
      "await proxy.dispose()", "'--include-runtime=false'", 'extra.length',
    ]) expect(script).toContain(protection);
    const frontend = JSON.parse(readFileSync(join(root, 'tsconfig.frontend.json'), 'utf8'));
    expect(frontend.compilerOptions.types).toEqual(['vite/client']);
    expect(frontend.include).not.toContain('src/worker/env.d.ts');
    const generated = readFileSync(join(root, 'src/worker/env.d.ts'), 'utf8');
    expect(generated).toContain('Generated by Wrangler');
    expect(generated).toContain('DB: D1Database');
    expect(generated).not.toContain('interface D1Database');
  });

  it('ignores local/private paths but permits only intentional example templates', () => {
    const temporary = mkdtempSync(join(tmpdir(), 'candidate-copilot-git-'));
    try {
      copyFileSync(join(root, '.gitignore'), join(temporary, '.gitignore'));
      execFileSync('git', ['init', '--quiet', temporary]);
      const ignored = execFileSync('git', ['check-ignore', '--no-index', '--stdin'], {
        cwd: temporary,
        input: `${ignoredPaths.join('\n')}\n.env.example\n.dev.vars.example\nfrontend/src/App.tsx\n`,
        encoding: 'utf8',
      }).trim().split('\n');
      expect(ignored).toEqual(ignoredPaths);
    } finally {
      rmSync(temporary, { recursive: true, force: true });
    }
  });

  it('has no tracked local secrets or private content', () => {
    const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' }).split('\0').filter(Boolean);
    const forbidden = tracked.filter((path) => {
      const segments = path.split('/');
      const name = segments.at(-1)!;
      return ['content/private/', 'dist/', 'coverage/', 'test-results/', 'playwright-report/'].some((prefix) => path.startsWith(prefix)) || segments.some((segment) => ['node_modules', '.wrangler', '.venv', 'venv'].includes(segment)) ||
        (/^(\.env|\.dev\.vars)/.test(name) && !['.env.example', '.dev.vars.example'].includes(name));
    });
    expect(forbidden).toEqual([]);
  });

  it('builds in a real terminal and cleans up bounded synthetic failures', () => {
    const output = execFileSync(process.execPath, ['scripts/check-build-interactivity.mjs'], {
      cwd: root,
      encoding: 'utf8',
      env: { ...process.env, CI: 'true' },
      // Two real build deadlines plus bounded synthetic failures and cleanup.
      timeout: 200_000,
    });
    expect(output).toContain('without skills prompt (fresh settings)');
    expect(output).toContain('without skills prompt (aged accepted metadata preserved)');
    for (const control of ['skills-install', 'skills-update', 'wrapped-install', 'generic-confirmation', 'deadline', 'output-limit', 'interruption', 'orphan']) {
      expect(output).toContain(`PASS: synthetic PTY ${control} rejected and cleaned (not Wrangler).`);
    }
  }, 210_000);

  it('keeps canaries out of both builds independently of Git ignores', () => {
    const output = execFileSync(process.execPath, ['scripts/check-build-isolation.mjs'], {
      cwd: root,
      encoding: 'utf8',
      timeout: 120_000,
    });
    expect(output).toContain('PASS: frontend and Worker artifacts exclude');
  });
});
